"""Upload a fine-tuned model folder to the Hugging Face Hub, with a model card.

Run once per model (in Colab, after training), with a WRITE token from
https://huggingface.co/settings/tokens:
    from huggingface_hub import login; login()
    python push_to_hub.py --model-dir $OUT/distilbert_b/model --repo akifkulll/mayi-distilbert-b \
        --input b --results $OUT/results/distilbert_b_test/metrics.json
"""

import argparse
import json
import os

from huggingface_hub import HfApi

CARD = """---
license: apache-2.0
language: en
base_model: distilbert-base-uncased
datasets:
- ProCreations/auto-1b-data
pipeline_tag: text-classification
---

# {repo}

`distilbert-base-uncased` fine-tuned to decide whether an AI agent's proposed tool call should be
**allowed (0)** or **denied (1)**. Input format **{input_upper}**: {input_desc}

Trained for the COE025 NLP course project (Istinye University) on the cleaned English split of
[auto-1b-data](https://huggingface.co/datasets/ProCreations/auto-1b-data)
([cleaning and splits](https://github.com/Enes-Ozbek/LucidAI-Dataset)).

## Test results (threshold 0.5)

{metrics}

## Use

```python
from transformers import pipeline
clf = pipeline("text-classification", model="{repo}")
clf("### PROPOSED TOOL CALL\\ntool: shell\\nargs: rm -rf node_modules ...")
```

Labels were generated by AI models; expect weaker results on inputs written in a different format.
"""

INPUTS = {"a": "the tool call alone.",
          "b": "the tool call, then the user's request, then the agent's earlier steps (max 512 tokens; the end of the history is cut)."}


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--model-dir", required=True)
    p.add_argument("--repo", required=True, help="user/name on the Hub")
    p.add_argument("--input", choices=["a", "b"], required=True)
    p.add_argument("--results", help="metrics.json from evaluate_predictions.py, shown in the card")
    p.add_argument("--private", action="store_true")
    a = p.parse_args()

    metrics = "Not evaluated yet."
    if a.results and os.path.exists(a.results):
        o = json.load(open(a.results))["overall"]
        metrics = ("| rows | accuracy | macro-F1 | false allow rate | false deny rate | AUROC |\n"
                   "|---:|---:|---:|---:|---:|---:|\n"
                   f"| {o['rows']} | {o['accuracy']:.4f} | {o['macro_f1']:.4f} | {o['false_allow_rate']:.4f} "
                   f"| {o['false_deny_rate']:.4f} | {o['auroc']:.4f} |")
    with open(os.path.join(a.model_dir, "README.md"), "w") as f:
        f.write(CARD.format(repo=a.repo, input_upper=a.input.upper(), input_desc=INPUTS[a.input], metrics=metrics))

    api = HfApi()
    api.create_repo(a.repo, private=a.private, exist_ok=True)
    api.upload_folder(folder_path=a.model_dir, repo_id=a.repo, commit_message="Upload fine-tuned model")
    print(f"https://huggingface.co/{a.repo}")


if __name__ == "__main__":
    main()
